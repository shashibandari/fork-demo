function dedupeWords(seeds: WordSeed[]): WordSeed[] {
  const seen = new Map<string, WordSeed>();

  for (const seed of seeds) {
    const key = seed.word.toUpperCase();
    const existing = seen.get(key);

    if (!existing || seed.frequencyScore > existing.frequencyScore) {
      seen.set(key, { ...seed, word: key });
    }
  }

  return Array.from(seen.values());
}

