function buildDictionaryEntry(
  word: string,
  categories: string[],
  frequencyScore: number,
  memorabilityScore: number,
  preferred = false
): DictionaryWord {
  return {
    word: word.toUpperCase(),
    digits: wordToDigits(word),
    categories,
    frequencyScore,
    memorabilityScore,
    preferred,
  };
}

